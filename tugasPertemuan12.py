
# luas persegi panjang
def luasPP(angka1, angka2):
    luas = angka1 * angka2
    print(f"Luas dari persegi panjang adalah {luas}")
luasPP(5, 8)

# volume balok
def volumePP(angka1, angka2, angka3):
    volume = angka1 * angka2 * angka3
    print(f"Volume dari balok adalah {volume}")
volumePP(5, 8, 10)

# luas lingkaran
def luasLingkaran(jari):
    pi = 3.14
    luasling = pi * (jari ** 2) 
    print(f"Luas dari lingkaran adalah {luasling}")
luasLingkaran(7)

# volume bola
def VolBola(jari):
    pi = 3.14
    Volbola = 4/3 * pi * (jari ** 3) 
    print(f"Volume dari bola adalah {Volbola}")
VolBola(7)